"""
Reward Script: Documentation workflow for ~/project
Task ID: vscode_wf_041
Domain: vscode
Scoring:
  Component 1 (0.30): README.md exists with all required sections
  Component 2 (0.15): README.md has a Table of Contents
  Component 3 (0.20): docs/architecture.md exists and describes project structure
  Component 4 (0.20): Extension yzhang.markdown-all-in-one is installed
  Component 5 (0.15): README.md has substantive content (code blocks, API tables)
"""

import os
import re
import subprocess

WORKDIR = '/home/user'
PROJECT = os.path.join(WORKDIR, 'project')
README_PATH = os.path.join(PROJECT, 'README.md')
ARCH_PATH = os.path.join(PROJECT, 'docs', 'architecture.md')
TASK_ID = 'vscode_wf_041'


def verify_task():
    """
    Verify task completion with progressive scoring.
    Returns: float between 0.0 and 1.0
    """
    total_score = 0.0

    # ------------------------------------------------------------------
    # Pre-check: README.md must exist to score anything README-related
    # ------------------------------------------------------------------
    readme_content = None
    if os.path.isfile(README_PATH):
        try:
            with open(README_PATH, 'r', encoding='utf-8') as f:
                readme_content = f.read()
        except Exception as e:
            print(f"ERROR: Could not read README.md: {e}")

    # ------------------------------------------------------------------
    # Component 1: README.md has all five required sections (0.30 pts)
    #   - Project Overview
    #   - Installation
    #   - Usage (with code blocks)
    #   - API Reference
    #   - Contributing
    # Each section found earns 0.06 pts (5 * 0.06 = 0.30)
    # ------------------------------------------------------------------
    required_sections = [
        (r'(?i)#.*project\s+overview|(?i)#.*overview', 'Project Overview'),
        (r'(?i)#.*installation', 'Installation'),
        (r'(?i)#.*usage', 'Usage'),
        (r'(?i)#.*api\s+reference', 'API Reference'),
        (r'(?i)#.*contribut', 'Contributing'),
    ]
    try:
        if readme_content is not None:
            sections_found = 0
            for pattern, name in required_sections:
                if re.search(pattern, readme_content):
                    sections_found += 1
                    print(f"  FOUND section: {name}")
                else:
                    print(f"  MISSING section: {name}")
            if sections_found == len(required_sections):
                total_score += sections_found * 0.06
                print(f"PASS: Component 1 — All {sections_found} required sections found (0.30 pts)")
            elif sections_found > 0:
                total_score += sections_found * 0.06
                print(f"PARTIAL: Component 1 — {sections_found}/{len(required_sections)} sections ({sections_found * 0.06:.2f} pts)")
            else:
                print("FAIL: Component 1 — No required sections found in README.md")
        else:
            print("FAIL: Component 1 — README.md does not exist")
    except Exception as e:
        print(f"ERROR: Component 1 — {e}")

    # ------------------------------------------------------------------
    # Component 2: README.md has a Table of Contents (0.15 pts)
    # The TOC generated by Markdown All in One uses markdown links like
    # "- [Section Name](#section-name)" format
    # ------------------------------------------------------------------
    try:
        if readme_content is not None:
            # Look for a TOC heading and at least 3 markdown anchor links
            has_toc_heading = bool(re.search(r'(?i)#+\s*table\s+of\s+contents', readme_content))
            toc_links = re.findall(r'-\s+\[.+?\]\(#.+?\)', readme_content)
            if has_toc_heading and len(toc_links) >= 3:
                print(f"PASS: Component 2 — Table of Contents found with {len(toc_links)} links (0.15 pts)")
                total_score += 0.15
            else:
                print(f"FAIL: Component 2 — TOC heading: {has_toc_heading}, TOC links: {len(toc_links)}")
        else:
            print("FAIL: Component 2 — README.md does not exist")
    except Exception as e:
        print(f"ERROR: Component 2 — {e}")

    # ------------------------------------------------------------------
    # Component 3: docs/architecture.md exists and describes project
    # structure (0.20 pts)
    # Must mention key directories (src/, tests/) and have reasonable length
    # ------------------------------------------------------------------
    try:
        if os.path.isfile(ARCH_PATH):
            with open(ARCH_PATH, 'r', encoding='utf-8') as f:
                arch_content = f.read()
            # Check that it actually describes the project structure
            mentions_src = bool(re.search(r'src/', arch_content))
            mentions_tests = bool(re.search(r'tests/', arch_content))
            has_substance = len(arch_content.strip()) >= 200
            if mentions_src and mentions_tests and has_substance:
                print(f"PASS: Component 3 — architecture.md exists and describes project structure (0.20 pts)")
                total_score += 0.20
            elif has_substance:
                # Partial: file exists with content but missing key references
                print(f"PARTIAL: Component 3 — architecture.md exists but missing src/ or tests/ references (0.10 pts)")
                total_score += 0.10
            else:
                print(f"FAIL: Component 3 — architecture.md exists but too short ({len(arch_content)} chars)")
        else:
            print("FAIL: Component 3 — docs/architecture.md does not exist")
    except Exception as e:
        print(f"ERROR: Component 3 — {e}")

    # ------------------------------------------------------------------
    # Component 4: Extension yzhang.markdown-all-in-one is installed
    # (0.20 pts)
    # ------------------------------------------------------------------
    try:
        result = subprocess.run(
            ['code', '--list-extensions'],
            capture_output=True, text=True, timeout=15
        )
        extensions = result.stdout.strip().lower()
        if 'yzhang.markdown-all-in-one' in extensions:
            print(f"PASS: Component 4 — yzhang.markdown-all-in-one extension installed (0.20 pts)")
            total_score += 0.20
        else:
            print(f"FAIL: Component 4 — Extension not found. Installed: {result.stdout.strip()}")
    except Exception as e:
        print(f"ERROR: Component 4 — {e}")

    # ------------------------------------------------------------------
    # Component 5: README.md has substantive content — code blocks and
    # structured content (0.15 pts)
    # Checks for fenced code blocks and either tables or lists
    # ------------------------------------------------------------------
    try:
        if readme_content is not None:
            code_blocks = re.findall(r'```[\s\S]*?```', readme_content)
            has_code_blocks = len(code_blocks) >= 2
            # Check for markdown tables (| col | col |)
            has_tables = bool(re.search(r'\|.*\|.*\|', readme_content))
            if has_code_blocks and has_tables:
                print(f"PASS: Component 5 — README has {len(code_blocks)} code blocks and tables (0.15 pts)")
                total_score += 0.15
            elif has_code_blocks:
                print(f"PARTIAL: Component 5 — README has code blocks but no tables (0.08 pts)")
                total_score += 0.08
            else:
                print(f"FAIL: Component 5 — README lacks code blocks ({len(code_blocks)} found)")
        else:
            print("FAIL: Component 5 — README.md does not exist")
    except Exception as e:
        print(f"ERROR: Component 5 — {e}")

    final_score = round(min(total_score, 1.0), 2)
    print(f"\nScore: {total_score:.2f}/1.0")
    print(f"REWARD: {final_score}")
    return final_score


verify_task()
