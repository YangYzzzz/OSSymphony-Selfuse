WORKDIR = '/home/user'
TASK_ID = 'vscode_td_031'
PROJECT_DIR = f'{WORKDIR}/projects/android-app'


def launch_gui(command: str, delay_sec: float = 1.0):
    """Launch GUI app on VM display without blocking script exit."""
    env = os.environ.copy()
    env["DISPLAY"] = ":0"
    subprocess.Popen(
        shlex.split(command),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )
    time.sleep(delay_sec)


def create_initial():
    # Create project directory structure
    os.makedirs(f'{PROJECT_DIR}/src/main/java/com/example/myapp', exist_ok=True)
    os.makedirs(f'{PROJECT_DIR}/src/test/java/com/example/myapp', exist_ok=True)
    os.makedirs(f'{PROJECT_DIR}/gradle/wrapper', exist_ok=True)

    # Ensure NO .vscode folder exists
    vscode_dir = f'{PROJECT_DIR}/.vscode'
    if os.path.exists(vscode_dir):
        import shutil
        shutil.rmtree(vscode_dir)

    # Create gradlew (executable shell script)
    gradlew_content = '''#!/bin/sh

#
# Gradle start up script for POSIX generated by Gradle.
#

APP_NAME="Gradle"
APP_BASE_NAME=$(basename "$0")

# Resolve links
PRG="$0"
while [ -h "$PRG" ]; do
    ls=$(ls -ld "$PRG")
    link=$(expr "$ls" : '.*-> \\(.*\\)$')
    if expr "$link" : '/.*' > /dev/null; then
        PRG="$link"
    else
        PRG=$(dirname "$PRG")/"$link"
    fi
done
SAVED="$(pwd)"
cd "$(dirname "$PRG")/" >/dev/null
APP_HOME="$(pwd -P)"
cd "$SAVED" >/dev/null

CLASSPATH=$APP_HOME/gradle/wrapper/gradle-wrapper.jar

exec java -classpath "$CLASSPATH" org.gradle.wrapper.GradleWrapperMain "$@"
'''
    with open(f'{PROJECT_DIR}/gradlew', 'w') as f:
        f.write(gradlew_content)
    os.chmod(f'{PROJECT_DIR}/gradlew', stat.S_IRWXU | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH)

    # Create build.gradle.kts
    build_gradle_content = '''plugins {
    id("com.android.application") version "8.2.0"
    id("org.jetbrains.kotlin.android") version "1.9.22"
}

android {
    namespace = "com.example.myapp"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.example.myapp"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }
}

dependencies {
    implementation("androidx.core:core-ktx:1.12.0")
    implementation("androidx.appcompat:appcompat:1.6.1")
    implementation("com.google.android.material:material:1.11.0")
    implementation("androidx.constraintlayout:constraintlayout:2.1.4")
    testImplementation("junit:junit:4.13.2")
    androidTestImplementation("androidx.test.ext:junit:1.1.5")
    androidTestImplementation("androidx.test.espresso:espresso-core:3.5.1")
}
'''
    with open(f'{PROJECT_DIR}/build.gradle.kts', 'w') as f:
        f.write(build_gradle_content)

    # Create settings.gradle.kts
    settings_gradle_content = '''pluginManagement {
    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}

dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google()
        mavenCentral()
    }
}

rootProject.name = "MyApp"
include(":app")
'''
    with open(f'{PROJECT_DIR}/settings.gradle.kts', 'w') as f:
        f.write(settings_gradle_content)

    # Create gradle.properties
    gradle_properties = '''# Project-wide Gradle settings.
org.gradle.jvmargs=-Xmx2048m -Dfile.encoding=UTF-8
android.useAndroidX=true
kotlin.code.style=official
android.nonTransitiveRClass=true
'''
    with open(f'{PROJECT_DIR}/gradle.properties', 'w') as f:
        f.write(gradle_properties)

    # Create a placeholder gradle-wrapper.jar (empty file for structure)
    with open(f'{PROJECT_DIR}/gradle/wrapper/gradle-wrapper.jar', 'wb') as f:
        f.write(b'')

    # Create gradle-wrapper.properties
    wrapper_props = '''distributionBase=GRADLE_USER_HOME
distributionPath=wrapper/dists
distributionUrl=https\\://services.gradle.org/distributions/gradle-8.4-bin.zip
networkTimeout=10000
validateDistributionUrl=true
zipStoreBase=GRADLE_USER_HOME
zipStorePath=wrapper/dists
'''
    with open(f'{PROJECT_DIR}/gradle/wrapper/gradle-wrapper.properties', 'w') as f:
        f.write(wrapper_props)

    # Create main Java source file
    main_activity = '''package com.example.myapp;

import android.os.Bundle;
import androidx.appcompat.app.AppCompatActivity;

public class MainActivity extends AppCompatActivity {

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        setContentView(R.layout.activity_main);
    }
}
'''
    with open(f'{PROJECT_DIR}/src/main/java/com/example/myapp/MainActivity.java', 'w') as f:
        f.write(main_activity)

    # Create a utility class
    utils_class = '''package com.example.myapp;

import java.util.ArrayList;
import java.util.List;

/**
 * Utility helper methods for the application.
 */
public class AppUtils {

    /**
     * Formats a price value to a display string.
     */
    public static String formatPrice(double price) {
        return String.format("$%.2f", price);
    }

    /**
     * Validates an email address format.
     */
    public static boolean isValidEmail(String email) {
        if (email == null || email.isEmpty()) {
            return false;
        }
        return email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$");
    }

    /**
     * Splits a full name into first and last name components.
     */
    public static String[] splitName(String fullName) {
        if (fullName == null || fullName.trim().isEmpty()) {
            return new String[]{"", ""};
        }
        String[] parts = fullName.trim().split("\\\\s+", 2);
        if (parts.length == 1) {
            return new String[]{parts[0], ""};
        }
        return parts;
    }
}
'''
    with open(f'{PROJECT_DIR}/src/main/java/com/example/myapp/AppUtils.java', 'w') as f:
        f.write(utils_class)

