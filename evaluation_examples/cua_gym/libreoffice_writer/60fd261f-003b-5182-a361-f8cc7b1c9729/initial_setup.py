import os
import shlex
import subprocess
import time
from docx import Document
from docx.shared import Pt
from docx.oxml.ns import qn

WORKDIR = '/home/user/Desktop'
TASK_ID = 'biology_paper'
OUTPUT = f'{WORKDIR}/{TASK_ID}.docx'


def launch_gui(command: str, delay_sec: float = 1.0):
    """Launch GUI app on VM display without blocking script exit."""
    env = os.environ.copy()
    env["DISPLAY"] = ":0"
    subprocess.Popen(
        shlex.split(command),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )
    time.sleep(delay_sec)


def create_initial():
    # Ensure Desktop directory exists
    os.makedirs(WORKDIR, exist_ok=True)

    doc = Document()

    # --- Title ---
    title_para = doc.add_heading('Cellular Mechanisms of Photosynthesis in C4 Plants', level=0)

    # Abstract
    doc.add_heading('Abstract', level=1)
    doc.add_paragraph(
        'This study investigates the biochemical pathways underlying photosynthesis in C4 plants, '
        'focusing on the role of PEP carboxylase and Rubisco in carbon fixation. We present '
        'comparative data from maize (Zea mays) and sorghum (Sorghum bicolor) under varying '
        'light intensities and CO2 concentrations. Results indicate a 34% increase in carbon '
        'fixation efficiency compared to C3 plants under high-temperature conditions.'
    )

    # Introduction
    doc.add_heading('Introduction', level=1)
    doc.add_paragraph(
        'Photosynthesis is the fundamental process by which plants convert light energy into '
        'chemical energy stored as glucose. C4 plants have evolved a specialized carbon '
        'concentrating mechanism that suppresses photorespiration and dramatically increases '
        'photosynthetic efficiency in hot, arid environments. This adaptation is particularly '
        'important in the context of global climate change, where increasing temperatures '
        'threaten agricultural productivity worldwide.'
    )
    doc.add_paragraph(
        'The C4 photosynthetic pathway was first described by Hatch and Slack in 1966, '
        'following their observations that certain tropical grasses incorporated CO2 into '
        'four-carbon organic acids rather than the three-carbon compounds typical of most plants. '
        'Since then, C4 photosynthesis has been identified in over 7,500 plant species across '
        'at least 62 independent lineages, suggesting strong convergent evolutionary pressure '
        'toward this efficient carbon fixation strategy.'
    )
    doc.add_paragraph(
        'Key enzymes involved in C4 photosynthesis include phosphoenolpyruvate carboxylase '
        '(PEPC), NADP-malate dehydrogenase, NADP-malic enzyme, and pyruvate orthophosphate '
        'dikinase (PPDK). These enzymes work in concert within the mesophyll and bundle sheath '
        'cells to concentrate CO2 around Rubisco, effectively suppressing its oxygenase activity '
        'and the energy-wasting process of photorespiration.'
    )

    # Methods
    doc.add_heading('Methods', level=1)
    doc.add_paragraph(
        'Plant material consisted of maize (Zea mays L. cv. B73) and sorghum (Sorghum bicolor '
        'L. cv. BTx623) seeds obtained from the USDA Plant Introduction Archive. Seeds were '
        'surface-sterilized with 10% bleach solution for 5 minutes, rinsed three times with '
        'sterile distilled water, and germinated on moistened filter paper at 28°C in the dark '
        'for 48 hours. Seedlings were then transferred to 2L pots containing a 3:1 mixture of '
        'potting soil and perlite.'
    )
    doc.add_paragraph(
        'Gas exchange measurements were performed using a LI-COR LI-6800 portable photosynthesis '
        'system. Leaves were equilibrated for 20 minutes at each measurement condition before '
        'recording values. Light response curves were generated by exposing fully expanded third '
        'leaves to photosynthetic photon flux densities (PPFD) ranging from 0 to 2000 μmol '
        'm⁻² s⁻¹ at 400 ppm CO2. CO2 response curves (A-Ci curves) were obtained at saturating '
        'light (1500 μmol m⁻² s⁻¹) with CO2 concentrations ranging from 50 to 1500 ppm.'
    )
    doc.add_paragraph(
        'Enzyme activity assays were conducted on freshly isolated leaf extracts. Leaf tissue '
        '(0.5 g) was ground in liquid nitrogen and resuspended in 2 mL extraction buffer '
        'containing 50 mM HEPES-KOH (pH 7.5), 10 mM MgCl2, 1 mM EDTA, 1 mM DTT, and '
        '0.1% (v/v) Triton X-100. Extracts were centrifuged at 14,000 × g for 5 minutes at 4°C, '
        'and the supernatant was used for enzyme assays. PEPC activity was measured '
        'spectrophotometrically at 340 nm by coupling the reaction to NADH oxidation.'
    )

    # Results
    doc.add_heading('Results', level=1)
    doc.add_paragraph(
        'Gas exchange measurements revealed significant differences between maize and sorghum '
        'under varying light conditions. At saturating light intensity (1500 μmol m⁻² s⁻¹), '
        'maize achieved a maximum net photosynthesis rate of 42.3 ± 3.1 μmol CO2 m⁻² s⁻¹, '
        'compared to 38.7 ± 2.8 μmol CO2 m⁻² s⁻¹ for sorghum. Both species significantly '
        'outperformed the C3 reference plant Arabidopsis thaliana, which showed a maximum rate '
        'of only 24.1 ± 1.9 μmol CO2 m⁻² s⁻¹ under identical conditions.'
    )
    doc.add_paragraph(
        'The light compensation point, at which gross photosynthesis equals respiration, was '
        'reached at approximately 45 μmol m⁻² s⁻¹ in both C4 species, compared to 28 μmol '
        'm⁻² s⁻¹ in Arabidopsis. This higher light compensation point reflects the additional '
        'ATP requirement of the C4 carbon-concentrating mechanism. However, the C4 plants '
        'showed much steeper increases in photosynthesis above the compensation point, reaching '
        'light saturation at approximately 800 μmol m⁻² s⁻¹ compared to 450 μmol m⁻² s⁻¹ '
        'in Arabidopsis.'
    )
    doc.add_paragraph(
        'PEPC activity in maize mesophyll extracts averaged 156.4 ± 12.3 nmol min⁻¹ mg⁻¹ '
        'protein, consistent with published values for C4 species. PPDK activity was '
        '89.2 ± 7.6 nmol min⁻¹ mg⁻¹ protein in light-adapted leaves, decreasing to '
        '23.1 ± 3.4 nmol min⁻¹ mg⁻¹ protein after 30 minutes of dark adaptation, confirming '
        'the light-regulated nature of this enzyme through reversible phosphorylation.'
    )

    # Discussion
    doc.add_heading('Discussion', level=1)
    doc.add_paragraph(
        'Our results demonstrate that both maize and sorghum maintain superior photosynthetic '
        'performance compared to C3 plants, particularly under high-temperature and high-light '
        'conditions characteristic of tropical agricultural environments. The 34% increase in '
        'maximum photosynthetic rate represents a significant advantage that directly translates '
        'to greater biomass accumulation and grain yield potential.'
    )
    doc.add_paragraph(
        'The high PEPC activity measured in mesophyll cells confirms the central role of this '
        'enzyme in initial CO2 fixation. The rapid deactivation of PPDK in the dark, and its '
        'reactivation upon illumination, demonstrates the fine-tuned regulatory mechanisms '
        'that allow C4 plants to respond rapidly to changing light environments. This regulatory '
        'flexibility may contribute to the superior performance of C4 crops under variable '
        'field conditions.'
    )
    doc.add_paragraph(
        'Interestingly, sorghum showed greater tolerance to water deficit stress than maize, '
        'maintaining positive carbon assimilation rates at leaf water potentials as low as '
        '-2.8 MPa, compared to -1.9 MPa for maize. This difference may relate to differences '
        'in stomatal control and osmotic adjustment capacity between the two species. '
        'Understanding these species-specific differences will be important for developing '
        'drought-tolerant crop varieties adapted to increasingly arid growing conditions.'
    )

    # Conclusion
    doc.add_heading('Conclusion', level=1)
    doc.add_paragraph(
        'This study provides comprehensive evidence for the superior photosynthetic efficiency '
        'of C4 plants under conditions of high temperature and light intensity. The coordinated '
        'activities of PEPC, PPDK, and associated enzymes in the C4 cycle create a CO2 '
        'concentrating mechanism that effectively eliminates photorespiration and maximizes '
        'carbon gain per unit light absorbed.'
    )
    doc.add_paragraph(
        'Future work should focus on elucidating the molecular mechanisms underlying the '
        'differential stress tolerance observed between maize and sorghum. Comparative '
        'transcriptomic and proteomic analyses may reveal key regulatory genes and proteins '
        'that could serve as targets for engineering enhanced stress tolerance into existing '
        'C4 crops. Additionally, the transfer of C4 photosynthesis genes into C3 staple crops '
        'such as rice and wheat represents a potentially transformative approach to improving '
        'global food security in the face of climate change.'
    )
    doc.add_paragraph(
        'In conclusion, our data support the continued development of C4 crops as a strategy '
        'for sustainable agriculture in warming climates. The fundamental biochemical insights '
        'gained from this study provide a foundation for future biotechnological interventions '
        'aimed at enhancing photosynthetic efficiency in economically important crop species.'
    )

    # References
    doc.add_heading('References', level=1)
    doc.add_paragraph(
        'Hatch, M. D., & Slack, C. R. (1966). Photosynthesis by sugar-cane leaves: '
        'A new carboxylation reaction and the pathway of sugar formation. '
        'Biochemical Journal, 101(1), 103-111.'
    )
    doc.add_paragraph(
        'Sage, R. F. (2004). The evolution of C4 photosynthesis. '
        'New Phytologist, 161(2), 341-370.'
    )
    doc.add_paragraph(
        'Furbank, R. T., & Taylor, W. C. (1995). Regulation of photosynthesis '
        'in C3 and C4 plants: A molecular approach. The Plant Cell, 7(7), 797-807.'
    )
    doc.add_paragraph(
        'Leegood, R. C. (2002). C4 photosynthesis: Principles of CO2 concentration '
        'and prospects for its introduction into C3 plants. '
        'Journal of Experimental Botany, 53(369), 581-590.'
    )

    doc.save(OUTPUT)
    print(f'Initial file created: {OUTPUT}')

    # GUI-ready startup: open the file in LibreOffice Writer
    launch_gui(f'libreoffice --writer "{OUTPUT}"', delay_sec=2.0)
    print('GUI_READY: launched LibreOffice Writer with DISPLAY=:0')


create_initial()
