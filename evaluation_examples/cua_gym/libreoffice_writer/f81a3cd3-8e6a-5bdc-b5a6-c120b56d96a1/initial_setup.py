OUTPUT = f'{WORKDIR}/{TASK_ID}.docx'


def launch_gui(command: str, delay_sec: float = 1.0):
    """Launch GUI app on VM display without blocking script exit."""
    env = os.environ.copy()
    env["DISPLAY"] = ":0"
    subprocess.Popen(
        shlex.split(command),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )
    time.sleep(delay_sec)


def create_initial():
    doc = Document()

    # Page setup
    section = doc.sections[0]
    section.page_width = Inches(8.5)
    section.page_height = Inches(11)
    section.left_margin = Inches(1)
    section.right_margin = Inches(1)
    section.top_margin = Inches(1)
    section.bottom_margin = Inches(1)

    # Title
    title = doc.add_heading('The Transformation of Modern Europe: 1850-1950', level=0)
    title.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    run = subtitle.add_run('A Historical Analysis')
    run.font.size = Pt(14)
    run.italic = True

    author = doc.add_paragraph()
    author.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    run = author.add_run('Dr. Eleanor Whitfield')
    run.font.size = Pt(12)

    dept = doc.add_paragraph()
    dept.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    run = dept.add_run('Department of History, University of Cambridge')
    run.font.size = Pt(11)
    run.italic = True

    doc.add_paragraph()  # spacing

    # Abstract
    doc.add_heading('Abstract', level=1)
    doc.add_paragraph(
        'This essay examines the sweeping transformations that reshaped the European '
        'continent between 1850 and 1950. Drawing on primary sources from national archives, '
        'parliamentary records, and private collections, it traces the interconnected forces '
        'of industrialisation, political upheaval, and cultural change that defined this '
        'turbulent century. The analysis pays particular attention to the role of institutional '
        'reform, colonial expansion, and the devastating impact of two world wars on European '
        'society and governance.'
    )

    # PAGE 2 area - Chapter 1
    doc.add_page_break()
    doc.add_heading('Chapter 1: The Industrial Revolution and Its Aftermath', level=1)

    doc.add_paragraph(
        'The mid-nineteenth century witnessed an unprecedented acceleration in industrial '
        'output across Western Europe. Britain, having established its dominance in textile '
        'manufacturing and iron production during the preceding decades, continued to expand '
        'its industrial capacity at a remarkable pace. The construction of railway networks '
        'transformed the physical and economic landscape of the continent, connecting '
        'previously isolated communities to major urban centres and facilitating the rapid '
        'movement of goods, labour, and ideas.'
    )

    doc.add_paragraph(
        'The social consequences of industrialisation were profound and far-reaching. '
        'Urban populations swelled as agricultural workers migrated to factory towns in '
        'search of employment. Living conditions in these new industrial centres were often '
        'deplorable, with overcrowded housing, inadequate sanitation, and rampant disease '
        'afflicting the working classes. The disparity between the wealth generated by '
        'industrial enterprise and the poverty endured by those who laboured in its service '
        'became one of the defining tensions of the era [1].'
    )

    doc.add_paragraph(
        'Reform movements emerged in response to these conditions, driven by a combination '
        'of humanitarian concern, religious conviction, and pragmatic political calculation. '
        'The Factory Acts of the 1840s and 1850s represented early attempts to regulate working '
        'conditions, limiting the hours that women and children could be employed and mandating '
        'basic safety provisions. These legislative measures, while modest in scope, established '
        'the principle that the state bore a responsibility for the welfare of its industrial '
        'workforce.'
    )

    doc.add_paragraph(
        'Continental Europe followed a somewhat different trajectory. Germany, unified under '
        'Prussian leadership in 1871, pursued an aggressive programme of industrialisation '
        'that within a generation had transformed it into a formidable economic power. The '
        'Ruhr Valley became the centre of a vast coal and steel complex, while cities such as '
        'Berlin, Hamburg, and Munich developed thriving manufacturing sectors. France, recovering '
        'from the humiliation of the Franco-Prussian War, modernised its economy more gradually, '
        'balancing industrial development with the preservation of its agricultural heritage.'
    )

    # PAGE 3 area - Chapter 2
    doc.add_page_break()
    doc.add_heading('Chapter 2: Empire and Expansion', level=1)

    doc.add_paragraph(
        'The latter half of the nineteenth century was marked by an extraordinary expansion '
        'of European imperial power. The so-called Scramble for Africa, which reached its '
        'peak in the 1880s and 1890s, saw the continent partitioned among European powers '
        'with little regard for existing political boundaries or cultural identities. Britain, '
        'France, Germany, Belgium, and Italy each carved out substantial colonial territories, '
        'justified by a combination of economic ambition, strategic calculation, and the '
        'paternalistic ideology of the civilising mission.'
    )

    doc.add_paragraph(
        'The material culture of empire was astonishingly rich and varied. European museums '
        'accumulated vast collections of artefacts, specimens, and artworks acquired through '
        'a mixture of purchase, gift, and outright appropriation. The British Museum alone '
        'added tens of thousands of items to its holdings during this period, many of which '
        'remain subjects of controversy and repatriation claims to this day [2].'
    )

    doc.add_paragraph(
        'The economic dimensions of imperialism were equally significant. Colonial territories '
        'provided raw materials for European industries, captive markets for manufactured goods, '
        'and opportunities for capital investment. The rubber plantations of the Congo, the '
        'diamond mines of South Africa, and the tea estates of India and Ceylon generated '
        'enormous profits for European investors, while the populations that laboured in these '
        'enterprises frequently endured conditions of severe exploitation.'
    )

    doc.add_paragraph(
        'Opposition to imperial expansion was neither absent nor insignificant. Within Europe, '
        'socialist and liberal critics challenged the morality and expense of colonial ventures. '
        'In the colonies themselves, resistance movements ranged from armed rebellion to '
        'sophisticated political campaigns for self-governance. The Indian National Congress, '
        'founded in 1885, represented one of the earliest and most influential examples of '
        'organised anti-colonial politics, laying the groundwork for the independence movements '
        'that would reshape the global order in the twentieth century.'
    )

    # PAGE 4 area - Chapter 3
    doc.add_page_break()
    doc.add_heading('Chapter 3: Political Transformation and Democratic Reform', level=1)

    doc.add_paragraph(
        'The political landscape of Europe underwent a dramatic transformation during the '
        'period under examination. The old order of aristocratic privilege and monarchical '
        'authority, already shaken by the revolutions of 1848, faced mounting challenges '
        'from democratic, nationalist, and socialist movements. The extension of the franchise, '
        'the growth of mass political parties, and the emergence of an independent press '
        'combined to create a new and more participatory political culture.'
    )

    doc.add_paragraph(
        'In Britain, the Reform Acts of 1867 and 1884 progressively widened the electorate, '
        'though full universal suffrage would not be achieved until 1928. The parliamentary '
        'debates surrounding these reforms were fierce and illuminating, revealing fundamental '
        'disagreements about the nature of citizenship, the capacity of ordinary people for '
        'political judgement, and the relationship between property and political rights. '
        'The records of these debates remain an invaluable source for understanding the '
        'intellectual and ideological currents of the period [3].'
    )

    doc.add_paragraph(
        'The rise of organised labour represented one of the most consequential political '
        'developments of the late nineteenth century. Trade unions, initially suppressed by '
        'restrictive legislation, gradually won legal recognition and political influence. '
        'The formation of the Labour Party in Britain, the Social Democratic Party in Germany, '
        'and their counterparts across Europe created a new axis of political competition, '
        'challenging the established Liberal and Conservative parties and introducing questions '
        'of economic justice and workers\u2019 rights into mainstream political discourse.'
    )

    doc.add_paragraph(
        'The emergence of women\u2019s suffrage movements added another dimension to the struggle '
        'for political reform. From the moderate campaigns of Millicent Fawcett\u2019s National '
        'Union of Women\u2019s Suffrage Societies to the militant tactics of the Pankhurst family\u2019s '
        'Women\u2019s Social and Political Union, women across Europe demanded recognition of their '
        'political rights. The First World War, which drew millions of women into industrial '
        'employment and public service, proved a decisive turning point in this long campaign.'
    )

    # PAGE 5 area - Continued Chapter 3 / Transition
    doc.add_page_break()
    doc.add_heading('Chapter 4: The Great War and Its Legacy', level=1)

    doc.add_paragraph(
        'The outbreak of war in August 1914 brought to a catastrophic conclusion the tensions '
        'and rivalries that had accumulated over the preceding decades. The system of alliances '
        'that bound the great powers together ensured that a regional conflict in the Balkans '
        'rapidly escalated into a continental and eventually global conflagration. The scale '
        'of destruction wrought by the war surpassed anything in previous human experience, '
        'with an estimated ten million soldiers killed and millions more wounded, displaced, '
        'or psychologically scarred.'
    )

    doc.add_paragraph(
        'The war transformed every aspect of European society. Governments assumed '
        'unprecedented control over economic production, labour markets, and public opinion. '
        'The distinction between military and civilian life dissolved as entire populations '
        'were mobilised for the war effort. Women entered the workforce in vast numbers, '
        'filling roles previously reserved for men and demonstrating capabilities that '
        'undermined longstanding assumptions about gender and ability.'
    )

    doc.add_paragraph(
        'The Treaty of Versailles, signed in June 1919, attempted to construct a new '
        'European order from the wreckage of the old. The dismemberment of the Austro-Hungarian '
        'and Ottoman Empires created a mosaic of new nation-states in Central and Eastern Europe, '
        'while the imposition of harsh reparations on Germany sowed the seeds of future '
        'conflict. The League of Nations, established to prevent future wars through collective '
        'security and diplomacy, struggled from the outset with the absence of the United States '
        'and the reluctance of member states to subordinate national interests to international '
        'cooperation.'
    )

    doc.add_paragraph(
        'The interwar period was characterised by political instability, economic volatility, '
        'and the rise of extremist ideologies. The Russian Revolution of 1917 had demonstrated '
        'the vulnerability of established political orders to revolutionary overthrow, and the '
        'spectre of Bolshevism haunted European politics throughout the 1920s and 1930s. '
        'Fascism, which emerged in Italy under Mussolini and reached its most destructive '
        'expression in Nazi Germany, offered a competing vision of authoritarian modernity '
        'that attracted millions of followers across the continent.'
    )

    # PAGE 6 area - Chapter 5
    doc.add_page_break()
    doc.add_heading('Chapter 5: The Interwar Crisis and the Press', level=1)

    doc.add_paragraph(
        'The role of the press in shaping public opinion during the interwar period cannot '
        'be overstated. Newspapers wielded enormous influence over popular attitudes towards '
        'domestic and foreign policy, and the proprietors of the great press empires were '
        'political figures in their own right. Lord Northcliffe, Lord Beaverbrook, and their '
        'continental counterparts used their publications to advocate for particular policies, '
        'support favoured politicians, and shape the terms of public debate.'
    )

    doc.add_paragraph(
        'The economic crisis of the 1930s brought these tensions to a head. The Wall Street '
        'Crash of 1929 and the subsequent global depression devastated European economies, '
        'producing mass unemployment, social dislocation, and political radicalisation. '
        'Contemporary newspaper accounts provide vivid testimony to the scale of human '
        'suffering and the inadequacy of governmental responses. The reporting of events '
        'such as the Jarrow March of 1936 and the general strikes that paralysed France '
        'and Spain helped to galvanise public sympathy for the plight of ordinary workers '
        'and their families [4].'
    )

    doc.add_paragraph(
        'The rise of radio broadcasting introduced a new dimension to mass communication. '
        'Politicians recognised the power of the medium to reach millions of listeners '
        'simultaneously, and the great orators of the era \u2014 Churchill, Hitler, de Gaulle \u2014 '
        'exploited it with devastating effectiveness. The BBC, founded in 1922, established '
        'itself as a model of public service broadcasting, committed to principles of '
        'impartiality and educational purpose that influenced broadcasting organisations '
        'around the world.'
    )

    doc.add_paragraph(
        'Censorship and propaganda became increasingly sophisticated during this period. '
        'Authoritarian regimes in Germany, Italy, and the Soviet Union exercised comprehensive '
        'control over their national media, suppressing dissent and constructing elaborate '
        'narratives of national destiny and racial superiority. Even in democratic states, '
        'governments deployed propaganda techniques developed during the First World War '
        'to manage public opinion and maintain social cohesion in the face of economic '
        'hardship and political uncertainty.'
    )

    # PAGE 7 area - Chapter 6
    doc.add_page_break()
    doc.add_heading('Chapter 6: Personal Histories and Private Collections', level=1)

    doc.add_paragraph(
        'The grand narratives of political and economic transformation are illuminated and '
        'enriched by the personal histories of those who lived through these momentous events. '
        'Diaries, letters, and memoirs provide an intimate perspective on the experience of '
        'ordinary individuals navigating extraordinary circumstances. The Morrison Collection, '
        'housed at the University of Edinburgh, is one of the most remarkable archives of '
        'this kind, comprising thousands of letters exchanged between members of a single '
        'Scottish family over three generations [5].'
    )

    doc.add_paragraph(
        'The collection spans the period from the 1860s to the 1940s, documenting the family\u2019s '
        'experiences of emigration, military service, industrial employment, and domestic life. '
        'Letters from the trenches of the Western Front sit alongside correspondence describing '
        'the daily routines of factory work and the pleasures of village life, creating a '
        'richly textured portrait of an era of profound change. The Morrison papers have been '
        'extensively catalogued and digitised, making them accessible to scholars worldwide.'
    )

    doc.add_paragraph(
        'Private collections of this kind serve as an essential corrective to the tendency '
        'of institutional histories to privilege the perspectives of political and economic '
        'elites. They remind us that the great events of the period were experienced not '
        'merely as abstract historical forces but as immediate, personal realities that '
        'shaped the lives, relationships, and aspirations of millions of individuals. The '
        'integration of personal testimony into historical analysis has enriched our '
        'understanding of the period immeasurably.'
    )

    # PAGE 8 area - Conclusion
    doc.add_page_break()
    doc.add_heading('Conclusion', level=1)

    doc.add_paragraph(
        'The century between 1850 and 1950 was one of the most transformative in European '
        'history. The forces of industrialisation, imperial expansion, democratic reform, '
        'and catastrophic warfare combined to reshape the continent\u2019s political, economic, '
        'and social structures in ways that continue to reverberate today. The institutions '
        'and ideologies that emerged from this period \u2014 the welfare state, human rights, '
        'European integration \u2014 represent both responses to its failures and attempts to '
        'build a more just and peaceful order.'
    )

    doc.add_paragraph(
        'The sources upon which this essay has drawn \u2014 parliamentary records, museum archives, '
        'newspaper accounts, and private correspondence \u2014 collectively testify to the richness '
        'and complexity of the European experience during this period. Each type of source '
        'offers a distinct perspective, and it is through the careful juxtaposition and '
        'critical analysis of these diverse materials that a comprehensive understanding '
        'of the past may be achieved.'
    )

    doc.add_paragraph(
        'As Europe continues to grapple with the legacies of its modern history \u2014 from '
        'questions of colonial restitution to the ongoing project of continental integration \u2014 '
        'the study of this formative period remains as relevant and necessary as ever. It is '
        'the hope of this author that the present essay may contribute, however modestly, to '
        'that vital and continuing conversation.'
    )

    doc.save(OUTPUT)
    print(f'Initial file created: {OUTPUT}')

    # GUI-ready startup
    launch_gui(f'libreoffice --writer "{OUTPUT}"', delay_sec=2.0)
    print('GUI_READY: launched LibreOffice Writer with DISPLAY=:0')


create_initial()
