def create_initial():
    os.makedirs(LEGAL_DIR, exist_ok=True)

    doc = pymupdf.open()

    # Create the first 10 detailed exhibit pages
    for title, body_lines in EVIDENCE_PAGES:
        page = doc.new_page(width=W, height=H)

        # Header line
        page.insert_text(
            pymupdf.Point(72, 50),
            "CONFIDENTIAL - ATTORNEY WORK PRODUCT",
            fontsize=8,
            fontname="cour",
            color=(0.5, 0.5, 0.5),
        )

        # Title
        page.insert_text(
            pymupdf.Point(72, 85),
            title,
            fontsize=14,
            fontname="hebo",
            color=(0, 0, 0),
        )

        # Separator line
        shape = page.new_shape()
        shape.draw_line(pymupdf.Point(72, 95), pymupdf.Point(W - 72, 95))
        shape.finish(color=(0, 0, 0), width=0.5)
        shape.commit()

        # Body text
        y = 120
        for line in body_lines:
            if y > H - 60:
                break
            page.insert_text(
                pymupdf.Point(72, y),
                line,
                fontsize=10,
                fontname="cour" if "---" in line or "  " == line[:2] else "helv",
                color=(0, 0, 0),
            )
            y += 14

    # Create supplementary exhibit pages (pages 11-45)
    for title, description in SUPPLEMENTARY_PAGES:
        page = doc.new_page(width=W, height=H)

        # Header
        page.insert_text(
            pymupdf.Point(72, 50),
            "CONFIDENTIAL - ATTORNEY WORK PRODUCT",
            fontsize=8,
            fontname="cour",
            color=(0.5, 0.5, 0.5),
        )

        # Title
        page.insert_text(
            pymupdf.Point(72, 85),
            title,
            fontsize=14,
            fontname="hebo",
            color=(0, 0, 0),
        )

        # Separator
        shape = page.new_shape()
        shape.draw_line(pymupdf.Point(72, 95), pymupdf.Point(W - 72, 95))
        shape.finish(color=(0, 0, 0), width=0.5)
        shape.commit()

        # Body as wrapped textbox
        rect = pymupdf.Rect(72, 120, W - 72, H - 60)
        page.insert_textbox(
            rect,
            description,
            fontsize=11,
            fontname="helv",
            color=(0, 0, 0),
            align=pymupdf.TEXT_ALIGN_LEFT,
        )

    doc.save(OUTPUT)
    doc.close()
    print(f'Initial file created: {OUTPUT}')
    print(f'Page count: 45')

    # Open in Evince for GUI-ready state
    launch_gui(f'evince "{OUTPUT}"', delay_sec=2.0)
    print('GUI_READY: launched evince with DISPLAY=:0')


create_initial()
