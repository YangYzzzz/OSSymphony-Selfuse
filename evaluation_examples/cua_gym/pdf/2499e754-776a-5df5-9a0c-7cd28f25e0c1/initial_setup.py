def launch_gui(command: str, delay_sec: float = 1.0):
    """Launch GUI app on VM display without blocking script exit."""
    env = os.environ.copy()
    env["DISPLAY"] = ":0"
    subprocess.Popen(
        shlex.split(command),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )
    time.sleep(delay_sec)


def create_page_content(page, title, subtitle, body_lines, page_num, total_pages):
    """Helper to add formatted legal content to a page."""
    width = page.rect.width
    height = page.rect.height

    # Header line
    shape = page.new_shape()
    shape.draw_line(pymupdf.Point(72, 60), pymupdf.Point(width - 72, 60))
    shape.finish(color=(0, 0, 0), width=1.5)
    shape.commit()

    # Title
    page.insert_text(
        pymupdf.Point(72, 50),
        title,
        fontsize=14,
        fontname="hebo",
        color=(0, 0, 0),
    )

    # Subtitle
    page.insert_text(
        pymupdf.Point(72, 85),
        subtitle,
        fontsize=11,
        fontname="tiit",
        color=(0.2, 0.2, 0.2),
    )

    # Body text
    y_pos = 120
    for line in body_lines:
        if y_pos > height - 80:
            break
        page.insert_text(
            pymupdf.Point(72, y_pos),
            line,
            fontsize=10,
            fontname="tiro",
            color=(0, 0, 0),
        )
        y_pos += 16

    # Footer
    footer_line_y = height - 50
    shape2 = page.new_shape()
    shape2.draw_line(pymupdf.Point(72, footer_line_y), pymupdf.Point(width - 72, footer_line_y))
    shape2.finish(color=(0.5, 0.5, 0.5), width=0.5)
    shape2.commit()

    page.insert_text(
        pymupdf.Point(72, height - 38),
        "Greenfield v. Meridian Properties LLC  |  Case No. 2025-CV-04821",
        fontsize=8,
        fontname="helv",
        color=(0.4, 0.4, 0.4),
    )
    page.insert_text(
        pymupdf.Point(width - 120, height - 38),
        f"Page {page_num} of {total_pages}",
        fontsize=8,
        fontname="helv",
        color=(0.4, 0.4, 0.4),
    )


