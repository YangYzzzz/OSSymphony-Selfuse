def create_initial():
    os.makedirs(LEGAL_DIR, exist_ok=True)
    os.makedirs(PLEADINGS_DIR, exist_ok=True)

    doc = pymupdf.open()

    all_sections = (
        generate_complaint_content()     # 12 pages
        + generate_answer_content()      # 8 pages
        + generate_counterclaim_content() # 5 pages
        + generate_reply_content()       # 7 pages
    )

    total_pages = len(all_sections)
    assert total_pages == 32, f"Expected 32 pages, got {total_pages}"

    for i, (title, subtitle, body_lines) in enumerate(all_sections):
        page = doc.new_page(width=612, height=792)  # US Letter
        create_page_content(page, title, subtitle, body_lines, i + 1, total_pages)

    doc.save(OUTPUT)
    doc.close()
    print(f'Initial file created: {OUTPUT}')
    print(f'Total pages: {total_pages}')
    print(f'Directory created: {PLEADINGS_DIR}')

    # Open the PDF in Evince for GUI-ready state
    launch_gui(f'evince "{OUTPUT}"', delay_sec=2.0)
    print('GUI_READY: launched evince with DISPLAY=:0')


create_initial()
