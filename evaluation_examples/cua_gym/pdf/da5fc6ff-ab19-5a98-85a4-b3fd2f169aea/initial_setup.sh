#!/usr/bin/env bash
set -euo pipefail

# ABSOLUTE TARGET DIRECTORY AND FILENAMES (extracted verbatim from task instruction)
TARGET_DIR="/home/user/Desktop"
PDF_NAME="neural_networks_2019.pdf"
PDF_PATH="${TARGET_DIR}/${PDF_NAME}"

# 1. Make sure the directory exists
mkdir -p "${TARGET_DIR}"

# 2. Install dependencies if they are missing
python3 - <<'PY'
import sys, subprocess, importlib.util

def ensure(pkg):
    if importlib.util.find_spec(pkg) is None:
        subprocess.check_call([sys.executable, "-m", "pip", "install", "--user", pkg])

ensure("reportlab")
ensure("PyPDF2")
PY

# 3. Generate a deterministic placeholder research paper
python3 <<'PY'
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak, Table, TableStyle
from reportlab.lib import colors

pdf_path = "/home/user/Desktop/neural_networks_2019.pdf"

doc             = SimpleDocTemplate(pdf_path, pagesize=LETTER,
                                    leftMargin=72, rightMargin=72,
                                    topMargin=72, bottomMargin=72)
styles          = getSampleStyleSheet()
story           = []

story.append(Paragraph("Neural Networks 2019: A Concise Survey", styles["Title"]))
story.append(Spacer(1, 24))

abstract = (
    "This document is a deterministic placeholder representing a 2019 survey on neural "
    "networks. It is generated by an automation script for testing PDF extraction."
)
story.append(Paragraph("Abstract", styles["Heading2"]))
story.append(Paragraph(abstract, styles["BodyText"]))
story.append(Spacer(1, 18))

story.append(Paragraph("1. Introduction", styles["Heading2"]))
intro = (
    "Artificial neural networks (ANNs) gained massive popularity in 2019 owing to "
    "advances in deep learning. This paper reviews core architectures, training "
    "paradigms, and applications."
)
story.append(Paragraph(intro, styles["BodyText"]))
story.append(Spacer(1, 18))

story.append(Paragraph("2. Architectures", styles["Heading2"]))
tbl_data = [
    ["Architecture", "Key Feature", "Year"],
    ["MLP", "Fully-connected layers", "1980s"],
    ["CNN", "Convolution & pooling", "1998"],
    ["RNN", "Temporal recurrence", "1986"],
    ["Transformer", "Self-attention", "2017"],
]
table = Table(tbl_data, colWidths=[120, 200, 60])
table.setStyle(TableStyle([
    ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#EFEFEF")),
    ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
    ("ALIGN", (0,0), (-1,-1), "CENTER"),
]))
story.append(table)
story.append(PageBreak())

story.append(Paragraph("3. Conclusion", styles["Heading2"]))
conclusion = (
    "Neural networks continue to evolve rapidly. The 2019 landscape demonstrates "
    "that architectural innovations and computational resources drive breakthroughs."
)
story.append(Paragraph(conclusion, styles["BodyText"]))

doc.build(story)
PY

echo "Initial PDF created at: ${PDF_PATH}"