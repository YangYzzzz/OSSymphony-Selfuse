def launch_gui(command: str, delay_sec: float = 1.0):
    """Launch GUI app on VM display without blocking script exit."""
    env = os.environ.copy()
    env["DISPLAY"] = ":0"
    subprocess.Popen(
        shlex.split(command),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )
    time.sleep(delay_sec)


def create_pdf(filepath, pages_content):
    """Create a PDF with given page contents. Each page has a title + body text."""
    doc = pymupdf.open()
    for title, body_lines in pages_content:
        page = doc.new_page(width=612, height=792)  # Letter size
        # Header line
        page.insert_text(
            pymupdf.Point(72, 60),
            title,
            fontsize=14,
            fontname="hebo",
            color=(0, 0, 0),
        )
        # Horizontal rule
        shape = page.new_shape()
        shape.draw_line(pymupdf.Point(72, 70), pymupdf.Point(540, 70))
        shape.finish(color=(0.3, 0.3, 0.3), width=0.5)
        shape.commit()
        # Body text
        y = 95
        for line in body_lines:
            if y > 740:
                break
            page.insert_text(
                pymupdf.Point(72, y),
                line,
                fontsize=10,
                fontname="helv",
                color=(0, 0, 0),
            )
            y += 14
    doc.save(filepath)
    doc.close()
    print(f"Created: {filepath} ({len(pages_content)} pages)")


