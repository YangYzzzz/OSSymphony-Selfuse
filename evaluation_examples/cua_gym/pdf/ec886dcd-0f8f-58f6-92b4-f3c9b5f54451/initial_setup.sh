#!/usr/bin/env bash
set -euo pipefail
#
# Initial script: creates a simple “application_form.pdf” on the Desktop.
# The PDF contains visible labels + values that will later be extracted.
#

# Absolute target directory and filenames (EXTRACTED DIRECTLY FROM TASK)
TARGET_DIR="/home/user/Desktop"
PDF_PATH="/home/user/Desktop/application_form.pdf"

# 1) Prepare directory
mkdir -p "${TARGET_DIR}"

# 2) Ensure dependencies are present
python3 - <<'PY'
import importlib, subprocess, sys

def ensure(pkg):
    try:
        importlib.import_module(pkg)
    except ImportError:
        subprocess.check_call([sys.executable, "-m", "pip", "install", "--user", pkg])

for lib in ("reportlab", "PyPDF2"):
    ensure(lib)
PY

# 3) Build the initial PDF with some realistic form text
python3 <<'PY'
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4

pdf_path = "/home/user/Desktop/application_form.pdf"
c = canvas.Canvas(pdf_path, pagesize=A4)

# Coordinates
x_margin, y_start = 72, 800
line_gap = 24

# Title
c.setFont("Helvetica-Bold", 18)
c.drawString(x_margin, y_start, "Application Form")

# Field labels + filled-in values
c.setFont("Helvetica", 12)
fields = [
    ("Full Name:", "John Doe"),
    ("Email:", "john.doe@example.com"),
    ("Phone:", "+1 555-1234"),
    ("Address:", "123 Main St, Springfield"),
]
y = y_start - 2 * line_gap
for label, value in fields:
    c.drawString(x_margin, y, f"{label} {value}")
    y -= line_gap

# Footer
c.setFont("Helvetica-Oblique", 10)
c.drawString(x_margin, 100, "Generated by ReportLab – Initial state")

c.save()
PY

echo "Initial PDF created at: ${PDF_PATH}"