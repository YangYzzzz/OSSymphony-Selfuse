# Reward script: verify conversion of map.pdf to map.svg
# -----------------------------------------------------
# This script awards a progressive score (0.0–1.0) based on
# concrete evidence that the PDF → SVG conversion task was
# completed.  Seven independent conditions are checked; each is
# worth 1/7 ≈ 0.1429 points, yielding a maximum of 1.0 when all
# conditions pass.
# -----------------------------------------------------

from pathlib import Path
import re
from PyPDF2 import PdfReader

PDF_PATH = Path("/home/user/Downloads/map.pdf")
SVG_PATH = Path("/home/user/Downloads/map.svg")


def verify_task() -> float:
    """Verify that map.pdf was converted to a valid map.svg.

    Returns
    -------
    float
        Reward score ∈ [0.0, 1.0].
    """

    conditions_passed = 0
    total_conditions = 7  # keep in sync with checks below

    # --------------------------------------------------
    # PDF checks
    # --------------------------------------------------
    if not PDF_PATH.exists():
        print(f"✗ Missing PDF file: {PDF_PATH}")
    else:
        try:
            reader = PdfReader(str(PDF_PATH))
            first_page = reader.pages[0] if reader.pages else None
            text = (first_page.extract_text() or "") if first_page else ""

            # 1) Exactly 1 page
            if len(reader.pages) == 1:
                conditions_passed += 1
                print("✓ PDF has exactly 1 page")
            else:
                print("✗ PDF does not have exactly 1 page")

            # 2) Contains title text 'Sample Map'
            if "Sample Map" in text:
                conditions_passed += 1
                print("✓ 'Sample Map' text found in PDF")
            else:
                print("✗ 'Sample Map' text missing in PDF")

            # 3) Contains build-marker text
            if "PDF rebuilt before SVG export" in text:
                conditions_passed += 1
                print("✓ Build-marker text found in PDF")
            else:
                print("✗ Build-marker text missing in PDF")

        except Exception as e:
            print(f"✗ Error reading PDF: {e}")

    # --------------------------------------------------
    # SVG checks
    # --------------------------------------------------
    if not SVG_PATH.exists():
        print(f"✗ Missing SVG file: {SVG_PATH}")
    else:
        try:
            content = SVG_PATH.read_text(encoding="utf-8", errors="ignore")

            # 4) SVG root present (xml prolog + <svg> tag)
            if content.lstrip().startswith("<?xml") and "<svg" in content:
                conditions_passed += 1
                print("✓ SVG root detected")
            else:
                print("✗ SVG root not detected")

            # 5) Correct canvas dimensions 595 × 842
            if re.search(r'width="?595"?', content) and re.search(r'height="?842"?', content):
                conditions_passed += 1
                print("✓ SVG dimensions 595×842 found")
            else:
                print("✗ SVG dimensions incorrect or missing")

            # 6) Deterministic comment marker present
            if "Deterministic SVG placeholder generated by golden script" in content:
                conditions_passed += 1
                print("✓ Deterministic comment found in SVG")
            else:
                print("✗ Deterministic comment missing in SVG")

            # 7) Basic vector elements (outer rect & grid line)
            if "<rect x=\"0\"" in content and "<line x1=\"0\"" in content:
                conditions_passed += 1
                print("✓ Basic vector elements present in SVG")
            else:
                print("✗ Basic vector elements missing in SVG")

        except Exception as e:
            print(f"✗ Error reading SVG: {e}")

    # --------------------------------------------------
    # Score calculation
    # --------------------------------------------------
    score = round(conditions_passed / total_conditions, 2)
    print(f"\nConditions passed: {conditions_passed}/{total_conditions}")
    print(f"REWARD: {score}")
    return score


if __name__ == "__main__":
    verify_task()
