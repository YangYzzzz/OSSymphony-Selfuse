def launch_gui(command: str, delay_sec: float = 1.0):
    """Launch GUI app on VM display without blocking script exit."""
    env = os.environ.copy()
    env["DISPLAY"] = ":0"
    subprocess.Popen(
        shlex.split(command),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )
    time.sleep(delay_sec)


def add_legal_page(doc, title, body_lines, page_width=612, page_height=792):
    """Add a page with a title and body text to the document."""
    page = doc.new_page(width=page_width, height=page_height)
    # Title
    page.insert_text(
        pymupdf.Point(72, 60),
        title,
        fontsize=16,
        fontname="hebo",
        color=(0, 0, 0),
    )
    # Horizontal rule under title
    shape = page.new_shape()
    shape.draw_line(pymupdf.Point(72, 70), pymupdf.Point(540, 70))
    shape.finish(color=(0, 0, 0), width=1)
    shape.commit()
    # Body text
    y = 100
    for line in body_lines:
        if y > 740:
            break
        rect = pymupdf.Rect(72, y, 540, y + 14)
        page.insert_textbox(rect, line, fontsize=10, fontname="helv", color=(0, 0, 0))
        y += 16
    return page


